# A set is a collection of unique values.
numbers = [10, 20, 10, 30, 20, 40, 50]
print(numbers)

# convert the list to set
set_numbers = set(numbers);
print(set_numbers);

# adding element to the set
set_numbers.add(60);
print(set_numbers);

# remove the element from the set
set_numbers.remove(60);
print(set_numbers);